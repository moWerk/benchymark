#!/usr/bin/env python3
# SailfishOS: turn src/benchy-mesh.js (the watch's JS table) into a C++
# header for the Wireframe item: the vertices, and every chain broken into
# line segments (index pairs), tagged with the strip they came from.
# usage: tools/mesh_to_header.py src/benchy-mesh.js > src/benchymesh.h
import re, sys, json
js = open(sys.argv[1]).read()
V = json.loads(re.search(r"var V = (\[.*?\]);", js, re.S).group(1))
S = json.loads(re.search(r"var S = (\[.*\]);", js, re.S).group(1))
segs = []
for b, bucket in enumerate(S):
    for chain in bucket:
        for i in range(len(chain) - 1):
            segs.append((chain[i], chain[i + 1], b))
print("// GENERATED by tools/mesh_to_header.py from src/benchy-mesh.js, do not edit.")
print("// 3DBenchy is public domain (NTI Group, 2025-02-14); credit to Creative Tools / NTI.")
print("// SPDX-License-Identifier: GPL-3.0-or-later")
print("#ifndef BENCHYMESH_H\n#define BENCHYMESH_H\n")
print("// %d vertices in a +/-1000 cube, %d segments (vertex, vertex, strip)" % (len(V) // 3, len(segs)))
print("static const int kBenchyVertexCount = %d;" % (len(V) // 3))
print("static const short kBenchyVertices[] = {")
for i in range(0, len(V), 18):
    print("    " + ",".join(str(v) for v in V[i:i + 18]) + ",")
print("};")
print("static const int kBenchySegmentCount = %d;" % len(segs))
print("static const unsigned char kBenchySegments[][3] = {")
for i in range(0, len(segs), 8):
    print("    " + ",".join("{%d,%d,%d}" % s for s in segs[i:i + 8]) + ",")
print("};\n\n#endif // BENCHYMESH_H")
